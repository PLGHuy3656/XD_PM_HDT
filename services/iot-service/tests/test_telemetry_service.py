# ==============================================================================
# TEST 19: MQTT DISPATCHER ROUTES TELEMETRY INTO TELEMETRYSERVICE
# ==============================================================================

def test_dispatcher_routes_telemetry_into_service(repo, valid_auto_payload_dict):
    mock_service = TelemetryService(repository=repo)
    dispatcher = MessageDispatcher(telemetry_svc=mock_service)

    topic = MQTTTopic(channel="telemetry", device_code="SWC-NODE-001")
    payload_bytes = json.dumps(valid_auto_payload_dict).encode("utf-8")

    dispatcher.dispatch(topic, payload_bytes)

    # Verify repository saved the record via TelemetryService
    saved = repo.get_latest("SWC-NODE-001")
    assert saved is not None
    assert saved.device_id == "SWC-NODE-001"
    assert saved.state.mode == "AUTO"


