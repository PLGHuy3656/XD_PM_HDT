# ==============================================================================
# TEST 1 & 2: VALID AUTO AND MANUAL TELEMETRY ACCEPTED
# ==============================================================================

def test_valid_auto_telemetry_accepted(service, repo, valid_auto_payload_dict):
    payload_bytes = json.dumps(valid_auto_payload_dict).encode("utf-8")
    result = service.process_message("SWC-NODE-001", payload_bytes)

    assert result.success is True
    assert result.telemetry is not None
    assert result.error is None

    assert result.telemetry.device_id == "SWC-NODE-001"
    assert result.telemetry.metrics.temperature == 29.2
    assert result.telemetry.metrics.humidity == 80.5
    assert result.telemetry.actuators.fan is True
    assert result.telemetry.state.mode == "AUTO"

    # Verify repository storage
    latest = repo.get_latest("SWC-NODE-001")
    assert latest == result.telemetry


def test_valid_manual_telemetry_accepted(service, repo, valid_auto_payload_dict):
    valid_auto_payload_dict["state"]["mode"] = "MANUAL"
    valid_auto_payload_dict["actuators"]["heater"] = True
    payload_bytes = json.dumps(valid_auto_payload_dict).encode("utf-8")

    result = service.process_message("SWC-NODE-001", payload_bytes)

    assert result.success is True
    assert result.telemetry.state.mode == "MANUAL"
    assert result.telemetry.actuators.heater is True


# ==============================================================================
# TEST 3: RECEIVED_AT GENERATED BY SERVER (UTC)
# ==============================================================================

def test_received_at_generated_by_server(service, valid_auto_payload_dict):
    before = datetime.now(timezone.utc)
    payload_bytes = json.dumps(valid_auto_payload_dict).encode("utf-8")
    result = service.process_message("SWC-NODE-001", payload_bytes)
    after = datetime.now(timezone.utc)

    assert result.success is True
    received_at = result.telemetry.received_at
    assert received_at.tzinfo == timezone.utc
    assert before <= received_at <= after


